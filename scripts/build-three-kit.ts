// `npm run build:three`: bundle three.js and the add-ons templates use into one plain script,
// templates/shared/three-kit.js. Templates can't load modules from the internet during a
// render, so they load this file from their own assets/ folder (`npm run sync:toolkit` copies
// it into every template that references assets/three-kit.js).
import { readFile } from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";

async function main(): Promise<void> {
  const root = process.cwd();
  const threePackage = JSON.parse(
    await readFile(path.join(root, "node_modules", "three", "package.json"), "utf8"),
  ) as { version: string };
  const licence = await readFile(path.join(root, "node_modules", "three", "LICENSE"), "utf8");
  const outfile = path.join(root, "templates", "shared", "three-kit.js");

  await build({
    entryPoints: [path.join(root, "scripts", "three-kit-entry.js")],
    outfile,
    bundle: true,
    format: "iife",
    globalName: "THREE_KIT",
    minify: true,
    target: "es2020",
    platform: "browser",
    legalComments: "none",
    banner: {
      js: [
        `/* three-kit: three.js ${threePackage.version} (https://threejs.org) plus add-ons,`,
        "   generated by `npm run build:three`; do not edit.",
        "",
        licence.trim(),
        "*/",
      ].join("\n"),
    },
    footer: {
      js: 'if (typeof module !== "undefined" && module.exports) module.exports = THREE_KIT;',
    },
  });
  console.log(`wrote ${path.relative(root, outfile)} (three.js ${threePackage.version})`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
