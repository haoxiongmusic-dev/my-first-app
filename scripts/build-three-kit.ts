// `npm run build:three`: bundle three.js and the add-ons templates use into one plain script,
// templates/shared/three-kit.js. Templates can't load modules from the internet during a
// render, so they load this file from their own assets/ folder (`npm run sync:toolkit` copies
// it into every template that references assets/three-kit.js).
import { readFile } from "node:fs/promises";
import path from "node:path";
import { build, type Plugin } from "esbuild";

/**
 * Templates must draw the same picture on every render, and `hyperframes check` rejects
 * scripts that call the browser's random generator or frame loop. three.js uses the random
 * generator only for object ids and some helpers, and its frame loop only for
 * `renderer.setAnimationLoop`, which templates never use. So inside three.js's own files:
 * - the random generator becomes a seeded one (`__threeKitRandom`, defined in the banner);
 * - the frame-loop functions are renamed (`frameLoopDisabled`, `frameLoopCancelDisabled`:
 *   harmless stubs defined in the banner), and the renderer's loop is never plugged into the
 *   window, so its start()/stop() do nothing. `renderer.dispose()` calls stop(); it must not
 *   reach a missing function.
 */
const UNPLUGGED_LOOP = "if ( typeof self !== 'undefined' ) animation.setContext( self );";
const deterministicThree: Plugin = {
  name: "deterministic-three",
  setup(b) {
    b.onLoad({ filter: /[\\/]node_modules[\\/]three[\\/].*\.js$/ }, async (args) => {
      const source = await readFile(args.path, "utf8");
      if (args.path.endsWith("three.module.js") && !source.includes(UNPLUGGED_LOOP)) {
        throw new Error("three.js changed: update UNPLUGGED_LOOP in build-three-kit.ts");
      }
      return {
        contents: source
          .replace(UNPLUGGED_LOOP, "/* three-kit: frame loop left unplugged */")
          .replaceAll("Math.random()", "__threeKitRandom()")
          .replaceAll("requestAnimationFrame", "frameLoopDisabled")
          .replaceAll("cancelAnimationFrame", "frameLoopCancelDisabled"),
        loader: "js",
      };
    });
  },
};

// A seeded generator (mulberry32, the same as the template toolkit's), seed 1.
const SEEDED_RANDOM = [
  "var __threeKitRandom = (function () {",
  "  var a = 1;",
  "  return function () {",
  "    a |= 0; a = (a + 0x6d2b79f5) | 0;",
  "    var t = Math.imul(a ^ (a >>> 15), 1 | a);",
  "    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;",
  "    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;",
  "  };",
  "})();",
  "// Stand-ins for the browser's frame loop, which three.js's own files no longer call.",
  "var frameLoopDisabled = function () { return 0; };",
  "var frameLoopCancelDisabled = function () {};",
].join("\n");

async function main(): Promise<void> {
  const root = process.cwd();
  const threePackage = JSON.parse(
    await readFile(path.join(root, "node_modules", "three", "package.json"), "utf8"),
  ) as { version: string };
  const licence = await readFile(path.join(root, "node_modules", "three", "LICENSE"), "utf8");
  const outfile = path.join(root, "templates", "shared", "three-kit.js");

  await build({
    entryPoints: [path.join(root, "scripts", "three-kit-entry.js")],
    outfile,
    bundle: true,
    format: "iife",
    globalName: "THREE_KIT",
    minify: true,
    target: "es2020",
    platform: "browser",
    legalComments: "none",
    plugins: [deterministicThree],
    banner: {
      js: [
        `/* three-kit: three.js ${threePackage.version} (https://threejs.org) plus add-ons,`,
        "   generated by `npm run build:three`; do not edit.",
        "",
        licence.trim(),
        "*/",
        SEEDED_RANDOM,
      ].join("\n"),
    },
    footer: {
      js: 'if (typeof module !== "undefined" && module.exports) module.exports = THREE_KIT;',
    },
  });
  console.log(`wrote ${path.relative(root, outfile)} (three.js ${threePackage.version})`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
